export function mockDesign(schema: Schema, namespace: string, name: string): TableDesign_Serialize {
  const rel = schema.namespaces.find((n) => n.name === namespace)?.tables.find((t) => t.name === name);
  if (!rel) throw new Error(`${name} not found`);
  const x = EXTRA[name] ?? {};
  const pk = rel.columns.filter((c) => c.primary_key).map((c) => c.name);
  return {
    namespace,
    name,
    comment: x.comment ?? null,
    columns: rel.columns.map((c) => ({ origin: c.name, name: c.name, type_name: c.type_name, nullable: c.nullable, default: x.defaults?.[c.name] ?? null, identity: x.identity === c.name, comment: x.comments?.[c.name] ?? null, default_name: null })),
    primary_key: pk,
    pk_name: pk.length ? `${name}_pkey` : null,
    indexes: [...rel.indexes.filter((i) => !(i.unique && i.columns.join() === pk.join())).map((i) => ({ origin: i.name, name: i.name, columns: [...i.columns], unique: i.unique, descending: [], expressions: [], predicate: null })), ...structuredClone(x.indexes ?? [])],
    foreign_keys: rel.foreign_keys.map((f) => ({ origin: f.name, name: f.name, columns: [...f.columns], ref_namespace: f.ref_namespace === namespace ? '' : f.ref_namespace, ref_table: f.ref_table, ref_columns: [...f.ref_columns], on_delete: f.on_delete, on_update: f.on_update })),
    checks: (x.checks ?? []).map(([n, e]) => ({ origin: n, name: n, expression: e })),
    triggers: (x.triggers ?? []).map(([n, sql]) => ({ name: n, sql })),
  };
}

const q = (e: DesignEngine, n: string) => (e === 'mysql' ? `\`${n.replaceAll('`', '``')}\`` : e === 'mssql' ? `[${n.replaceAll(']', ']]')}]` : `"${n.replaceAll('"', '""')}"`);
const lit = (s: string) => `'${s.replaceAll("'", "''")}'`;
const blank = (s: string | null | undefined) => !s || !s.trim();

export function mockDesignScript(e: DesignEngine, before: TableDesign | null, after: TableDesign): DesignScript {
  const out: string[] = [];
  const notes: DesignNote[] = [];
  const note = (code: DesignNote['code'], subject: string | null = null) => {
    if (!notes.some((n) => n.code === code && n.subject === subject)) notes.push({ code, subject, detail: null });
  };
  if (blank(after.name)) note('invalid', 'table');
  if (!after.columns.length) note('invalid', 'columns');
  const seen = new Set<string>();
  for (const c of after.columns) {
    if (blank(c.name)) note('invalid', 'column_name');
    else if (seen.has(c.name.toLowerCase())) note('invalid', c.name);
    seen.add(c.name.toLowerCase());
    if (blank(c.type_name)) note('invalid', c.name || 'column_type');
  }
  for (const i of after.indexes) if (blank(i.name) || !i.columns.length) note('invalid', i.name || 'index');
  for (const f of after.foreign_keys) if (blank(f.ref_table) || !f.columns.length || f.columns.length !== f.ref_columns.length || f.ref_columns.some(blank)) note('invalid', f.name || 'foreign_key');
  for (const c of after.checks) if (blank(c.expression)) note('invalid', c.name || 'check');
  if (notes.length) return { statements: [], notes, rebuild: false };

  const ns = after.namespace;
  const t = (n: string) => (e === 'sqlite' || !ns ? q(e, n) : `${q(e, ns)}.${q(e, n)}`);
  const list = (cs: string[]) => cs.map((c) => q(e, c)).join(', ');
  const def = (c: TableDesign['columns'][number]) => {
    let s = `${q(e, c.name)} ${c.type_name}`;
    if (c.identity && (e === 'postgres' || e === 'cockroach')) s += ' GENERATED BY DEFAULT AS IDENTITY';
    if (c.identity && e === 'mssql') s += ' IDENTITY(1,1)';
    if (!c.nullable) s += ' NOT NULL';
    if (c.identity && e === 'mysql') s += ' AUTO_INCREMENT';
    if (!blank(c.default) && !c.identity) s += ` DEFAULT ${c.default}`;
    if (e === 'mysql' && !blank(c.comment)) s += ` COMMENT ${lit(c.comment ?? '')}`;
    return s;
  };
  const fk = (f: TableDesign['foreign_keys'][number]) => {
    let s = `CONSTRAINT ${q(e, f.name)} FOREIGN KEY (${list(f.columns)}) REFERENCES ${t(f.ref_table)} (${list(f.ref_columns)})`;
    for (const [w, a] of [['DELETE', f.on_delete], ['UPDATE', f.on_update]] as [string, FkAction][]) if (a !== 'no_action') s += ` ON ${w} ${FK_SQL[a]}`;
    return s;
  };
  const create = (as: string) => {
    const parts = after.columns.map(def);
    if (after.primary_key.length) parts.push(`PRIMARY KEY (${list(after.primary_key)})`);
    for (const c of after.checks) parts.push(`CONSTRAINT ${q(e, c.name)} CHECK (${c.expression})`);
    for (const f of after.foreign_keys) parts.push(fk(f));
    return `CREATE TABLE ${t(as)} (\n  ${parts.join(',\n  ')}\n)`;
  };
  const index = (i: TableDesign['indexes'][number]) => {
    const parts = i.columns.map((c, k) => `${i.expressions?.[k] ? `(${c})` : q(e, c)}${i.descending?.[k] ? ' DESC' : ''}`).join(', ');
    let s = `CREATE ${i.unique ? 'UNIQUE ' : ''}INDEX ${q(e, i.name)} ON ${t(after.name)} (${parts})`;
    if (!blank(i.predicate)) {
      if (e === 'mysql' || e === 'duckdb') note('partial_unsupported', i.name);
      else s += ` WHERE ${i.predicate}`;
    }
    return s;
  };
  const shape = (i: TableDesign['indexes'][number]) => JSON.stringify([i.unique, i.columns.map((_, k) => [!!i.descending?.[k], !!i.expressions?.[k]]), (i.predicate ?? '').trim()]);
  const comment = (what: string, from: string | null | undefined, to: string | null | undefined) => {
    if ((from ?? '') === (to ?? '')) return;
    if (e === 'sqlite') return note('comment_unsupported');
    if (e === 'postgres' || e === 'cockroach' || e === 'duckdb') out.push(`COMMENT ON ${what} IS ${blank(to) ? 'NULL' : lit(to ?? '')}`);
  };
  if (!before) {
    out.push(create(after.name));
    for (const i of after.indexes) out.push(index(i));
    comment(`TABLE ${t(after.name)}`, null, after.comment);
    return { statements: out, notes, rebuild: false };
  }

  const old = (c: { origin?: string | null }) => before.columns.find((b) => b.name === c.origin);
  const dropped = before.columns.filter((b) => !after.columns.some((c) => c.origin === b.name));
  const kept = after.columns.filter((c) => old(c));
  const order = kept.map((c) => c.origin).join();
  const natural = before.columns.filter((b) => !dropped.includes(b)).map((b) => b.name).join();
  const added = after.columns.filter((c) => !old(c));
  const tailAdds = after.columns.slice(after.columns.length - added.length).every((c) => !old(c));
  const changed = kept.filter((c) => {
    const b = old(c);
    return b && (b.type_name !== c.type_name || b.nullable !== c.nullable || (b.default ?? '') !== (c.default ?? '') || b.identity !== c.identity);
  });
  const sameList = <T,>(a: T[], b: T[], key: (x: T) => string) => a.length === b.length && a.every((x, i) => key(x) === key(b[i] as T));
  const constraints = !sameList(before.checks, after.checks, (c) => c.name + c.expression) || !sameList(before.foreign_keys, after.foreign_keys, (f) => JSON.stringify([f.name, f.columns, f.ref_table, f.ref_columns, f.on_delete, f.on_update]));
  const pkChanged = before.primary_key.map((p) => after.columns.find((c) => c.origin === p)?.name ?? '').join() !== after.primary_key.join();

  if ((e === 'sqlite' || e === 'duckdb') && (changed.length || constraints || pkChanged || order !== natural || !tailAdds)) {
    const gone = [...dropped.map((d) => d.name), ...kept.flatMap((c) => (c.origin && c.origin !== c.name ? [c.origin] : []))];
    const triggers = e === 'sqlite' ? (before.triggers ?? []) : [];
    const blocks = triggers.flatMap((tr) => {
      const what = gone.find((g) => new RegExp(`\\b${g}\\b`, 'i').test(tr.sql));
      return what ? [{ code: 'trigger_blocks' as const, subject: tr.name, detail: what }] : [];
    });
    if (blocks.length) return { statements: [], notes: blocks, rebuild: true };
    note('rebuild', after.name);
    for (const d of dropped) note('drops_data', d.name);
    const tmp = `${after.name}_nd_new`;
    if (e === 'sqlite') out.push('PRAGMA defer_foreign_keys = ON');
    out.push(create(tmp));
    out.push(`INSERT INTO ${t(tmp)} (${kept.map((c) => q(e, c.name)).join(', ')})\nSELECT ${kept.map((c) => q(e, c.origin ?? '')).join(', ')} FROM ${t(before.name)}`);
    out.push(`DROP TABLE ${t(before.name)}`);
    out.push(`ALTER TABLE ${t(tmp)} RENAME TO ${q(e, after.name)}`);
    for (const i of after.indexes) out.push(index(i));
    for (const tr of triggers) {
      note('trigger_recreated', tr.name);
      out.push(tr.sql);
    }
    return { statements: out, notes, rebuild: true };
  }

  const alter = (s: string) => out.push(`ALTER TABLE ${t(after.name)} ${s}`);
  for (const f of before.foreign_keys) if (!after.foreign_keys.some((x) => x.origin === f.name && JSON.stringify([x.columns, x.ref_table, x.ref_columns, x.on_delete, x.on_update]) === JSON.stringify([f.columns, f.ref_table, f.ref_columns, f.on_delete, f.on_update]))) alter(e === 'mysql' ? `DROP FOREIGN KEY ${q(e, f.name)}` : `DROP CONSTRAINT ${q(e, f.name)}`);
  for (const c of before.checks) if (!after.checks.some((x) => x.origin === c.name && x.expression === c.expression)) alter(`DROP CONSTRAINT ${q(e, c.name)}`);
  const renamed = (cs: string[]) => cs.map((c) => after.columns.find((x) => x.origin === c)?.name ?? '');
  const follow = (text: string) => after.columns.reduce((t, c) => (c.origin && c.origin !== c.name ? renameIn(t, c.origin, c.name) : t), text);
  const moved = (i: TableDesign['indexes'][number]) => i.columns.map((c, k) => (i.expressions?.[k] ? follow(c) : (after.columns.find((x) => x.origin === c)?.name ?? ''))).join();
  const movedShape = (i: TableDesign['indexes'][number]) => shape({ ...i, predicate: i.predicate ? follow(i.predicate) : i.predicate });
  for (const i of before.indexes) if (!after.indexes.some((x) => x.origin === i.name && shape(x) === movedShape(i) && x.columns.join() === moved(i))) out.push(e === 'mysql' || e === 'mssql' ? `DROP INDEX ${q(e, i.name)} ON ${t(after.name)}` : `DROP INDEX ${t(i.name)}`);
  if (pkChanged && before.primary_key.length) alter(e === 'mysql' ? 'DROP PRIMARY KEY' : `DROP CONSTRAINT ${q(e, before.pk_name ?? `${before.name}_pkey`)}`);
  if (before.name !== after.name) out.push(`ALTER TABLE ${t(before.name)} RENAME TO ${q(e, after.name)}`);
  const moves = kept.flatMap((c) => {
    const b = old(c);
    return b && b.name !== c.name ? [[b.name, c.name] as const] : [];
  });
  const taken = (n: string) => before.columns.some((b) => b.name.toLowerCase() === n.toLowerCase());
  const later: (readonly [string, string])[] = [];
  for (const [from, to] of moves.filter(([, to]) => taken(to))) {
    note('rename_via_temp', from);
    alter(`RENAME COLUMN ${q(e, from)} TO ${q(e, `${from}_nd_tmp`)}`);
    later.push([`${from}_nd_tmp`, to]);
  }
  for (const [from, to] of [...moves.filter(([, to]) => !taken(to)), ...later]) alter(`RENAME COLUMN ${q(e, from)} TO ${q(e, to)}`);
  for (const d of dropped) {
    note('drops_data', d.name);
    alter(`DROP COLUMN ${q(e, d.name)}`);
  }
  for (const c of added) {
    if (!c.nullable && blank(c.default) && !c.identity) note('not_null_needs_value', c.name);
    alter(`${e === 'mssql' ? 'ADD' : 'ADD COLUMN'} ${def(c)}`);
  }
  for (const c of changed) {
    const b = old(c);
    if (!b) continue;
    const col = q(e, c.name);
    if (b.type_name !== c.type_name) note('type_change', c.name);
    if (e === 'mysql') alter(`MODIFY COLUMN ${def(c)}`);
    else if (e === 'mssql') alter(`ALTER COLUMN ${col} ${c.type_name} ${c.nullable ? 'NULL' : 'NOT NULL'}`);
    else {
      if (b.type_name !== c.type_name) alter(`ALTER COLUMN ${col} TYPE ${c.type_name}${e === 'postgres' ? ` USING ${col}::${c.type_name}` : ''}`);
      if (b.nullable !== c.nullable) alter(`ALTER COLUMN ${col} ${c.nullable ? 'DROP' : 'SET'} NOT NULL`);
      if ((b.default ?? '') !== (c.default ?? '')) alter(blank(c.default) ? `ALTER COLUMN ${col} DROP DEFAULT` : `ALTER COLUMN ${col} SET DEFAULT ${c.default}`);
    }
  }
  if (order !== natural || !tailAdds) note(e === 'mysql' ? 'reorder_rewrites' : 'reorder_unsupported', e === 'mysql' ? (after.columns[0]?.name ?? null) : null);
  if (pkChanged && after.primary_key.length) alter(`ADD PRIMARY KEY (${list(after.primary_key)})`);
  for (const i of after.indexes) {
    const b = before.indexes.find((x) => x.name === i.origin);
    if (!b || movedShape(b) !== shape(i) || moved(b) !== i.columns.join()) out.push(index(i));
  }
  for (const c of after.checks) if (!before.checks.some((x) => x.name === c.origin && x.expression === c.expression)) alter(`ADD CONSTRAINT ${q(e, c.name)} CHECK (${c.expression})`);
  for (const f of after.foreign_keys) if (!before.foreign_keys.some((x) => x.name === f.origin && JSON.stringify([x.columns, x.ref_table, x.ref_columns, x.on_delete, x.on_update]) === JSON.stringify([renamed(f.columns), f.ref_table, f.ref_columns, f.on_delete, f.on_update]))) alter(`ADD ${fk(f)}`);
  for (const c of kept) if (e !== 'mysql') comment(`COLUMN ${t(after.name)}.${q(e, c.name)}`, old(c)?.comment, c.comment);
  comment(`TABLE ${t(after.name)}`, before.comment, after.comment);
  return { statements: out, notes, rebuild: false };
}

export function b15Mock(schemaOf: (sid: string) => Promise<Schema>) {
  return {
    tableDesign: async (sid: string, namespace: string, name: string) => {
      await sleep(80);
      return mockDesign(await schemaOf(sid), namespace, name);
    },
    tableDesignScript: async (engine: DesignEngine, before: TableDesign | null, after: TableDesign) => mockDesignScript(engine, before, after),
  };
}
