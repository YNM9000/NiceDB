import type { Schema } from './api';
import type { Dialect, Relation_Serialize as Relation } from './bindings';
import type { ObjectRef } from './ddl';
import { quoteName } from './sqlname';

const PG_TYPES: Record<string, string> = { int4: 'integer', int8: 'bigint', bpchar: 'character(11)', bool: 'boolean', numeric: 'numeric(12,2)' };
const ACTION = { no_action: '', restrict: ' ON DELETE RESTRICT', cascade: ' ON DELETE CASCADE', set_null: ' ON DELETE SET NULL', set_default: ' ON DELETE SET DEFAULT' } as const;

function relationOf(schema: Schema, o: ObjectRef): Relation | undefined {
  const ns = schema.namespaces.find((n) => n.name === o.namespace);
  return [...(ns?.tables ?? []), ...(ns?.views ?? [])].find((r) => r.name === (o.kind === 'index' ? o.table : o.name));
}

function defaultOf(type: string, name: string): string {
  if (type === 'bool') return " DEFAULT false";
  if (type === 'date') return ' DEFAULT CURRENT_DATE';
  if (type === 'numeric' && /sconto|fido/.test(name)) return ' DEFAULT 0';
  return '';
}

const label = (name: string) => name.charAt(0).toUpperCase() + name.slice(1).replaceAll('_', ' ');

function checkOf(rel: Relation): string[] {
  return rel.columns.filter((c) => c.type_name === 'numeric' && /quantita|prezzo|totale|fido/.test(c.name)).map((c) => `CONSTRAINT ${rel.name}_${c.name}_check CHECK (${c.name} >= 0)`);
}

function postgresTable(ns: string, rel: Relation): string {
  const q = `${ns}.${rel.name}`;
  const lines = rel.columns.map((c, i) => {
    const type = PG_TYPES[c.type_name] ?? c.type_name;
    const identity = i === 0 && c.primary_key && /^int/.test(c.type_name) ? ' GENERATED BY DEFAULT AS IDENTITY' : '';
    return `    ${quoteName('postgres', c.name)} ${type}${identity}${defaultOf(c.type_name, c.name)}${c.nullable ? '' : ' NOT NULL'}`;
  });
  const pk = rel.columns.filter((c) => c.primary_key).map((c) => c.name);
  if (pk.length) lines.push(`    CONSTRAINT ${rel.name}_pkey PRIMARY KEY (${pk.join(', ')})`);
  lines.push(...checkOf(rel).map((c) => `    ${c}`));
  for (const fk of rel.foreign_keys) lines.push(`    CONSTRAINT ${fk.name} FOREIGN KEY (${fk.columns.join(', ')}) REFERENCES ${fk.ref_namespace === ns ? '' : `${fk.ref_namespace}.`}${fk.ref_table}(${fk.ref_columns.join(', ')})${ACTION[fk.on_delete]}`);
  const indexes = rel.indexes.filter((i) => i.name !== `${rel.name}_pkey`).map((i) => `CREATE ${i.unique ? 'UNIQUE ' : ''}INDEX ${i.name} ON ${q} USING btree (${i.columns.join(', ')});`);
  return [`CREATE TABLE ${q} (\n${lines.join(',\n')}\n);`, ...indexes, `COMMENT ON TABLE ${q} IS '${label(rel.name)}';`].join('\n\n');
}

function sqliteTable(rel: Relation): string {
  const lines = rel.columns.map((c) => `  ${c.name} ${c.type_name.toUpperCase()}${c.primary_key ? ' PRIMARY KEY' : ''}${c.nullable ? '' : ' NOT NULL'}${defaultOf(c.type_name, c.name)}`);
  return `CREATE TABLE ${rel.name} (\n${lines.join(',\n')}\n);`;
}

function view(d: Dialect, ns: string, rel: Relation): string {
  const cols = rel.columns.map((c) => c.name).join(',\n    ');
  if (d === 'sqlite') return `CREATE VIEW ${rel.name} AS\nSELECT ${cols}\n  FROM fatture\n WHERE NOT pagata;`;
  return `CREATE OR REPLACE VIEW ${ns}.${rel.name} AS\nSELECT f.${cols}\n   FROM ${ns}.fatture f\n  WHERE NOT f.pagata AND f.scadenza <= (CURRENT_DATE + 30);`;
}

function routine(ns: string, o: ObjectRef): string {
  const args = o.signature ?? '';
  return `CREATE OR REPLACE FUNCTION ${ns}.${o.name}(${args})
 RETURNS numeric
 LANGUAGE sql
 STABLE
AS $function$
  SELECT COALESCE(sum(f.totale), 0)
    FROM ${ns}.fatture f
   WHERE f.cliente_id = cid AND NOT f.pagata
$function$;`;
}

export function mockDdl(dialect: Dialect, schema: Schema, o: ObjectRef): string {
  const ns = o.namespace;
  switch (o.kind) {
    case 'table': {
      const rel = relationOf(schema, o);
      if (!rel) throw new Error(`${o.name} not found`);
      return dialect === 'sqlite' ? sqliteTable(rel) : postgresTable(ns, rel);
    }
    case 'view': {
      const rel = relationOf(schema, o);
      if (!rel) throw new Error(`${o.name} not found`);
      return view(dialect, ns, rel);
    }
    case 'routine':
      return routine(ns, o);
    case 'index': {
      const rel = relationOf(schema, o);
      const index = rel?.indexes.find((i) => i.name === o.name);
      if (!rel || !index) throw new Error(`${o.name} not found`);
      if (index.name === `${rel.name}_pkey`) return `ALTER TABLE ${ns}.${rel.name} ADD CONSTRAINT ${index.name} PRIMARY KEY (${index.columns.join(', ')});`;
      return `CREATE ${index.unique ? 'UNIQUE ' : ''}INDEX ${index.name} ON ${ns}.${rel.name} USING btree (${index.columns.join(', ')});`;
    }
    case 'trigger':
      return `CREATE TRIGGER ${o.name} AFTER INSERT OR DELETE OR UPDATE ON ${ns}.${o.table ?? 'righe_ordine'} FOR EACH ROW EXECUTE FUNCTION ${ns}.${o.name}_fn();`;
    case 'sequence':
      return `CREATE SEQUENCE ${ns}.${o.name}\n    AS bigint\n    INCREMENT BY 1\n    MINVALUE 1\n    MAXVALUE 9223372036854775807\n    START WITH 1000\n    CACHE 1;`;
  }
}
